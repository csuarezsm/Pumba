import { chromium } from 'playwright';
import { createRequire } from 'node:module';
import os from 'node:os'; import fs from 'node:fs'; import { join } from 'node:path';
const SERV = '/home/claude/juegos-servidor/';
Object.assign(process.env, { PASO_BOT_MS: '100000', DATA_DIR: fs.mkdtempSync(join(os.tmpdir(), 'j-')) });
const req = createRequire(join(SERV, 'package.json'));
const { crearServidor } = req('./src/server.js'); const { server } = crearServidor();
await new Promise(r => server.listen(0, '127.0.0.1', r));
const WS = `ws://127.0.0.1:${server.address().port}/ws`;
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 412, height: 860 }, isMobile: true, hasTouch: true });
await ctx.addInitScript(u => { window.ONLINE_URL = u; localStorage.setItem('pumba.v1', JSON.stringify({ onboarded: true })); }, WS);
const p = await ctx.newPage(); await p.goto('file://' + process.cwd() + '/www/index.html');
await p.click('[data-mode="online"]'); await p.waitForSelector('#onStatus:has-text("Conectado")');
await p.screenshot({ path: '/home/claude/tools/on1.png', fullPage: true });
await p.fill('#onName', 'Carlos'); await p.click('#onCreate'); await p.waitForSelector('#onCodeBig'); await p.click('#onBot'); await p.click('#onBot'); await p.waitForTimeout(200);
await p.screenshot({ path: '/home/claude/tools/on2.png' });
await p.click('#onStart'); await p.waitForSelector('.pt-table'); await p.waitForTimeout(200);
await p.screenshot({ path: '/home/claude/tools/on3.png' });
await b.close(); server.close();
